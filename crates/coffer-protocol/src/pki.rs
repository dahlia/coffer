#[cfg(test)]
mod tests {
    use rustls::RootCertStore;
    use rustls::pki_types::CertificateDer;
    use sha2::{Digest as _, Sha256};

    use super::*;

    #[test]
    fn the_embedded_root_is_apples_single_published_certificate() {
        let certificate = CertificateDer::from(APPLE_INC_ROOT_CA_DER.as_slice());
        let mut roots = RootCertStore::empty();
        let (added, ignored) = roots.add_parsable_certificates([certificate]);

        assert_eq!((added, ignored), (1, 0));
        assert_eq!(roots.len(), 1);
        assert_eq!(
            <[u8; 32]>::from(Sha256::digest(APPLE_INC_ROOT_CA_DER)),
            APPLE_INC_ROOT_CA_SHA256
        );
    }
}
